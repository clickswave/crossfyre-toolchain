/// Decode one header block. The dynamic table starts empty, which holds for the
/// first request on a connection.
pub fn decode(block: &[u8]) -> Vec<(String, String)> {
    let mut dynamic: Vec<(String, String)> = Vec::new();
    let mut out = Vec::new();
    let mut p = 0;
    while p < block.len() {
        let b = block[p];
        if b & 0x80 != 0 {
            let index = integer(block, &mut p, 7);
            out.push(lookup(index, &dynamic));
        } else if b & 0xe0 == 0x20 {
            // Dynamic table size update; nothing to keep for one block.
            integer(block, &mut p, 5);
        } else {
            let incremental = b & 0x40 != 0;
            let index = integer(block, &mut p, if incremental { 6 } else { 4 });
            let name = if index == 0 {
                string(block, &mut p)
            } else {
                lookup(index, &dynamic).0
            };
            let value = string(block, &mut p);
            if incremental {
                dynamic.insert(0, (name.clone(), value.clone()));
            }
            out.push((name, value));
        }
    }
    out
}

fn lookup(index: usize, dynamic: &[(String, String)]) -> (String, String) {
    assert!(index > 0, "HPACK index 0");
    if index <= STATIC_TABLE.len() {
        let (n, v) = STATIC_TABLE[index - 1];
        (n.to_string(), v.to_string())
    } else {
        dynamic[index - STATIC_TABLE.len() - 1].clone()
    }
}

/// RFC 7541 section 5.1.
fn integer(b: &[u8], p: &mut usize, prefix: u32) -> usize {
    let mask = (1usize << prefix) - 1;
    let mut value = b[*p] as usize & mask;
    *p += 1;
    if value < mask {
        return value;
    }
    let mut shift = 0;
    loop {
        let byte = b[*p];
        *p += 1;
        value += ((byte & 0x7f) as usize) << shift;
        shift += 7;
        if byte & 0x80 == 0 {
            return value;
        }
    }
}

/// RFC 7541 section 5.2.
fn string(b: &[u8], p: &mut usize) -> String {
    let huffman = b[*p] & 0x80 != 0;
    let len = integer(b, p, 7);
    let raw = &b[*p..*p + len];
    *p += len;
    let bytes = if huffman {
        huffman_decode(raw)
    } else {
        raw.to_vec()
    };
    String::from_utf8(bytes).expect("header text is UTF-8")
}

fn huffman_decode(data: &[u8]) -> Vec<u8> {
    let codes: HashMap<(u32, u8), usize> = HUFFMAN
        .iter()
        .enumerate()
        .map(|(sym, &(code, len))| ((code, len), sym))
        .collect();
    let mut out = Vec::new();
    let (mut code, mut len) = (0u32, 0u8);
    for byte in data {
        for shift in (0..8).rev() {
            code = (code << 1) | u32::from((byte >> shift) & 1);
            len += 1;
            if let Some(&sym) = codes.get(&(code, len)) {
                assert!(sym < 256, "EOS inside a Huffman string");
                out.push(sym as u8);
                code = 0;
                len = 0;
            }
        }
    }
    // What is left is padding: fewer than eight bits, all ones.
    assert!(len < 8 && code == (1 << len) - 1, "bad Huffman padding");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn decodes_the_rfc_7541_request_examples() {
        // Appendix C.4.1, first request with Huffman coding.
        let block = [
            0x82, 0x86, 0x84, 0x41, 0x8c, 0xf1, 0xe3, 0xc2, 0xe5, 0xf2, 0x3a, 0x6b, 0xa0, 0xab,
            0x90, 0xf4, 0xff,
        ];
        let want = [
            (":method", "GET"),
            (":scheme", "http"),
            (":path", "/"),
            (":authority", "www.example.com"),
        ];
        let got = decode(&block);
        assert_eq!(got.len(), want.len());
        for ((n, v), (wn, wv)) in got.iter().zip(want) {
            assert_eq!((n.as_str(), v.as_str()), (wn, wv));
        }
    }
}
